export type TranslationKey = keyof typeof translations['en'];

/** Map a scheduled-activity type to its localized label key. */
export function activityTypeLabelKey(type: string): TranslationKey {
  switch (String(type).toLowerCase()) {
    case 'call': return 'activityCall';
    case 'meeting': return 'activityMeeting';
    case 'follow_up':
    case 'followup': return 'activityFollowUp';
    case 'task': return 'activityTask';
    default: return 'activityFollowUp';
  }
}

export function useTranslation() {
  const { language, setLanguage } = useLanguageStore();

  const t = (key: TranslationKey, variables?: Record<string, string | number>): string => {
    const dict = translations[language] || translations['en'];
    let text = dict[key] ?? translations['en'][key] ?? String(key);

    if (variables) {
      Object.entries(variables).forEach(([vKey, vVal]) => {
        text = text.split(`{${vKey}}`).join(String(vVal));
      });
    }
    return text;
  };

  /** Convenience: localize an activity type label (call/meeting/follow_up/task). */
  const activityLabel = (type: string): string => t(activityTypeLabelKey(type));

  return { t, language, setLanguage, activityLabel };
}
